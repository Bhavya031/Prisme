"""Write BENCHMARK.md from data/results/entire-benchmark.json and the model settings in src/prism/models.py.

Run: python scripts/benchmark_page.py
"""

import json
import statistics
import sys
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from prism import models  # noqa: E402

data = json.loads((ROOT / "data/results/entire-benchmark.json").read_text())
summary = data["summary"]
PROVIDERS = ("claude", "openai")
PASSES = ("results", "repeat_2")
NAMES = {p: f"{p.capitalize() if p == 'claude' else 'OpenAI'} `{models.PRICES[p]['model']}`" for p in PROVIDERS}
cases = [c for c in data["cases"] if not c.get("excluded_from_scoring")]
excluded = [c for c in data["cases"] if c.get("excluded_from_scoring")]
predictions = len(cases) * len(PASSES)  # per provider

# Self-check: the page must agree with the summary the JSON already carries.
assert len(cases) == summary["cases"] and len(excluded) == summary["excluded_cases"]
assert summary["recorded_entire_sourced"] == summary["recorded_predictions"] == summary["recorded_trace_ids"]
for p in PROVIDERS:
    s = summary["providers"][p]
    assert abs(statistics.mean(c[k][p]["recall"] for c in cases for k in PASSES) - s["mean_recall"]) < 1e-9
    assert abs(sum(c[k][p]["estimated_cost_usd"] for c in cases for k in PASSES) - s["estimated_cost_usd"]) < 1e-6
assert len({c[k][p]["neatlogs_trace_id"] for c in data["cases"] for k in PASSES for p in PROVIDERS}) == summary["recorded_trace_ids"]
assert all(c[k][p]["discovery"]["source"] == "entire" for c in data["cases"] for k in PASSES for p in PROVIDERS)


def pct(value):
    return f"{value * 100:.1f}%"


def gh(url):
    return url.removeprefix("https://github.com/")


def issue_link(c):
    repo, number = c["issue_url"].split("/")[-3], c["issue_url"].rsplit("/", 1)[1]
    return f"[{repo} #{number}]({c['issue_url']})"


def pr_link(c):
    return f"[#{c['pr_url'].rsplit('/', 1)[1]}]({c['pr_url']})"


def snapshot_link(c):
    name = c["entire_repo"].rsplit("/", 1)[1]
    return f"[{name}@{c['snapshot_sha'][:12]}]({c['snapshot_repo']}/tree/{c['snapshot_sha']})"


def rp(c, p):
    return " → ".join(f"{c[k][p]['recall'] * 100:.0f}/{c[k][p]['precision'] * 100:.0f}" for k in PASSES)


claude, openai = (summary["providers"][p] for p in PROVIDERS)
lines = [
    "# Entire file-prediction benchmark",
    "",
    f"Run {data['date']} at Prism commit [`{data['source_commit'][:7]}`](https://github.com/Bhavya031/Prisme/commit/{data['source_commit']}). "
    "Raw data: [`data/results/entire-benchmark.json`](data/results/entire-benchmark.json). "
    "This page is generated by [`scripts/benchmark_page.py`](scripts/benchmark_page.py).",
    "",
    "## Findings",
    "",
    f"{summary['cases']} scored issues × {summary['repeats']} repeats × {len(PROVIDERS)} models = "
    f"{summary['predictions']} scored predictions ({summary['recorded_predictions']} recorded, including the excluded case). "
    f"All {summary['recorded_entire_sourced']} recorded predictions used `discovery.source=entire`.",
    "",
    f"| | {NAMES['claude']} | {NAMES['openai']} |",
    "|---|---:|---:|",
    f"| Mean recall | {pct(claude['mean_recall'])} | {pct(openai['mean_recall'])} |",
    f"| Mean precision | {pct(claude['mean_precision'])} | {pct(openai['mean_precision'])} |",
    f"| Exact file sets | {claude['exact_matches']} / {predictions} | {openai['exact_matches']} / {predictions} |",
    f"| Scored spend ({predictions} predictions) | ${claude['estimated_cost_usd']:.4f} | ${openai['estimated_cost_usd']:.4f} |",
    f"| Spend per file prediction | {claude['estimated_cost_usd'] / predictions * 100:.2f}¢ | {openai['estimated_cost_usd'] / predictions * 100:.2f}¢ |",
    f"| Total spend incl. excluded case | ${data['estimated_spend_usd']['claude']:.4f} | ${data['estimated_spend_usd']['openai']:.4f} |",
]
for label, key in (("recall", "mean_recall"), ("precision", "mean_precision")):
    cells = [" → ".join(pct(r[key]) for r in summary["providers"][p]["per_repeat"]) for p in PROVIDERS]
    lines.append(f"| Repeat 1 → 2 {label} | {cells[0]} | {cells[1]} |")
cells = [" → ".join(str(r["exact_matches"]) for r in summary["providers"][p]["per_repeat"]) for p in PROVIDERS]
lines.append(f"| Repeat 1 → 2 exact sets | {cells[0]} | {cells[1]} |")
recorded = [(c, k, p) for c in data["cases"] for k in PASSES for p in PROVIDERS]
timed = [(c[k][p]["neatlogs_timing"], p) for c, k, p in recorded if c[k][p]["neatlogs_timing"]["seconds"] is not None]
secs = {p: [t["seconds"] for t, q in timed if q == p] for p in PROVIDERS}
cells = [f"{statistics.median(secs[p]):.1f} s ({min(secs[p]):.1f}–{max(secs[p]):.1f} s, {len(secs[p])} / {len(recorded) // 2} traces)" for p in PROVIDERS]
lines.append(f"| Time per prediction, median (min–max) | {cells[0]} | {cells[1]} |")
starts = [datetime.fromisoformat(t["started_at"]) for t, _ in timed]
ends = [datetime.fromisoformat(t["started_at"]) + timedelta(seconds=t["seconds"]) for t, _ in timed]
first, last = recorded[0], recorded[-1]  # the runner went in this order, one prediction at a time
assert all(c[k][p]["neatlogs_timing"]["seconds"] is not None for c, k, p in (first, last))
wall = (max(ends) - min(starts)).total_seconds()
lines += [
    "",
    "Means weight each scored prediction equally. Spend is a token × list-price estimate (see Setup), not a provider invoice.",
    "",
    f"**Time (benchmark):** per-prediction time is the NeatLogs trace latency of the prediction's workflow span "
    f"(model calls plus Entire searches; issue-context collection ran before the span). "
    f"{len(recorded) - len(timed)} of {len(recorded)} traces return HTTP 404 from the NeatLogs read API, so they have no time. "
    f"Total wall time: {wall:.0f} s ({wall / 60:.1f} min) from the first prediction's start to the last one's end, "
    f"{len(recorded)} predictions run one at a time. Stored per prediction as `neatlogs_timing` in the JSON.",
    "",
    "**Speed (live workflow):** GitHub Actions runs of *Prism automated estimation and allocation* on "
    "[Bhavya031/flask](https://github.com/Bhavya031/flask/actions) triggered by an opened issue took 167–187 s "
    "from run start to finish; the run posts the estimate comment, allocates in CFO.ai and reports the allocation on the issue "
    "(runs 38526742471, 38527311380, 38527854554 on 2026-10-14; `gh run list -R Bhavya031/flask`). "
    "This is the live bot, not the benchmark runner.",
    "",
    "### By project",
    "",
    "| Snapshot | Issues | Claude recall / precision | OpenAI recall / precision |",
    "|---|---:|---:|---:|",
]
for repo in dict.fromkeys(c["entire_repo"] for c in cases):
    group = [c for c in cases if c["entire_repo"] == repo]
    cells = [
        " / ".join(pct(statistics.mean(c[k][p][field] for c in group for k in PASSES)) for field in ("recall", "precision"))
        for p in PROVIDERS
    ]
    lines.append(f"| {snapshot_link(group[0])} | {len(group)} | {cells[0]} | {cells[1]} |")

lines += ["", "### 0% recall predictions", "", "| Issue | Model | Repeat | Predicted | Real fix changed |", "|---|---|---:|---|---|"]
for c in cases:
    for n, k in enumerate(PASSES, 1):
        for p in PROVIDERS:
            if c[k][p]["recall"] == 0:
                predicted = ", ".join(f"`{f}`" for f in c[k][p]["predicted"]) or "(none)"
                lines.append(f"| {issue_link(c)} | {p} | {n} | {predicted} | {', '.join(f'`{f}`' for f in c['actual_files'])} |")

lines += ["", "### Excluded case", ""]
for c in excluded:
    scores = "; ".join(f"{p} {rp(c, p)}" for p in PROVIDERS)
    lines.append(
        f"{issue_link(c)} with fix PR {pr_link(c)}: excluded from scoring, reason recorded as "
        f"*{c['exclusion_reason']}*. Its {len(PASSES) * len(PROVIDERS)} predictions stay in the JSON "
        f"(recall/precision %, repeat 1 → 2: {scores}) and count only in total spend."
    )

lines += [
    "",
    "## Setup",
    "",
    *[
        f"- **{NAMES[p]}** via {models.APIS[p]}: effort `{models.EFFORT}`, max {models.MAX_TOKENS} output tokens per call, "
        f"strict JSON-schema output, up to 1 extra search round (`pipeline.predict(ctx, provider, max_extra=1)`)."
        for p in PROVIDERS
    ],
    "- **Search:** Entire code search only, no git fallback. Each model proposes literal terms; every term runs as "
    "`entire search --code --repo gh/prism-benchmarks/<name> --json --limit 30 -- <term>` "
    "([`src/prism/entire.py`](src/prism/entire.py)). Hits outside the snapshot's file tree are dropped.",
    "- **Entire repos:** " + ", ".join(
        f"`{c['entire_repo']}` @ [`{c['snapshot_sha'][:12]}`]({c['snapshot_repo']}/tree/{c['snapshot_sha']})"
        for c in {c["entire_repo"]: c for c in data["cases"]}.values()
    ) + ". Before any paid call, each snapshot repo's `main` had to equal its SHA and `entire repo view` had to report ready.",
    "- **Issue context:** issue text, plus comments and referenced items created before the fix PR was opened; lines that mention the fix PR are removed.",
    "- **Ground truth:** files the fix PR lists with status `modified` that exist in the snapshot tree "
    "(`github_context.true_files`); added and deleted files are not counted.",
    "- **Scoring per prediction:** recall = |predicted ∩ truth| / |truth|; precision = |predicted ∩ truth| / |predicted| "
    "(0 when nothing is predicted); exact = predicted set equals truth.",
    "- **Cost:** per call, (uncached input × input price + cached input × cached price + cache writes × cache-write price "
    "+ output × output price) / 1M, with `models.PRICES` (USD per 1M tokens): "
    + "; ".join(
        f"`{models.PRICES[p]['model']}` input {models.PRICES[p]['input']}, cached {models.PRICES[p]['cached_input']}, "
        f"cache write {models.PRICES[p]['cache_write']}, output {models.PRICES[p]['output']}"
        for p in PROVIDERS
    ) + ". Claude input tokens exclude cache reads; OpenAI cached tokens are subtracted from input. Reasoning tokens are part of output.",
    f"- **Caps:** ${data['caps_usd']['claude']:.2f} per model for the whole run. Before each call the runner refused to send "
    "if spend so far plus a conservative bound ((prompt + system + schema bytes + 10k) × $2.5/M + max output × $10/M) would cross the cap.",
    f"- **Tracing:** every prediction ran inside one NeatLogs workflow span; {summary['recorded_trace_ids']} unique trace IDs are recorded.",
    "- **Runner:** [`scripts/entire_benchmark.py`](scripts/entire_benchmark.py), the script that produced the raw results, kept as run "
    "(its paths point at the machine it ran on). The flask #3193 exclusion and the `summary` block were added to the JSON afterwards "
    "([701c860](https://github.com/Bhavya031/Prisme/commit/701c860bb0ea0a6d8abbaca2b212c641e1ce7edf), "
    "[006ec9f](https://github.com/Bhavya031/Prisme/commit/006ec9fc166608b2575de54130cf3fe2052f1015)).",
    "",
    "**Reproduce** (spends real model credit; edit `ROOT`, the `.env` path and the Entire token path at the top of the runner first):",
    "",
    "```sh",
    f"git checkout {data['source_commit']} && pip install -e .",
    "git checkout main -- scripts/entire_benchmark.py",
    "python scripts/entire_benchmark.py trial    # first case, both models, waits for the NeatLogs trace",
    "python scripts/entire_benchmark.py full     # repeat 1 for every case",
    "python scripts/entire_benchmark.py repeat2  # repeat 2 for every case",
    "git checkout main && python scripts/benchmark_page.py  # rewrite this page",
    "```",
    "",
    "## Cases",
    "",
    "R/P = recall/precision %, repeat 1 → repeat 2. Open a case below the table for its predictions, NeatLogs trace IDs and Entire queries.",
    "",
    "| Issue | Fix PR | Snapshot | Claude R/P | OpenAI R/P |",
    "|---|---|---|---:|---:|",
]
for c in data["cases"]:
    mark = " (excluded)" if c.get("excluded_from_scoring") else ""
    lines.append(f"| {issue_link(c)}{mark} | {pr_link(c)} | {snapshot_link(c)} | {rp(c, 'claude')} | {rp(c, 'openai')} |")

lines += [
    "",
    "NeatLogs trace IDs are listed per prediction. The NeatLogs app ([app.neatlogs.com](https://app.neatlogs.com)) requires a login "
    "to the project that holds them, so they are IDs, not public links. Spot check: trace `67c9533a3ac1e1017c3bc4ccb8e95835` "
    "(flask #3193, Claude, repeat 1) reads back from the NeatLogs ingest API with the same 7945 input / 404 output tokens as the JSON.",
    "",
]
for c in data["cases"]:
    lines += [
        "<details>",
        f"<summary>{c['id']} — truth: {', '.join(c['actual_files'])}</summary>",
        "",
        "| Model | Repeat | R/P | Time | Predicted | NeatLogs trace | Entire queries (hits) |",
        "|---|---:|---:|---:|---|---|---|",
    ]
    for n, k in enumerate(PASSES, 1):
        for p in PROVIDERS:
            r = c[k][p]
            queries = "<br>".join(f"`{t.replace('|', '&#124;')}` ({h})" for t, h in r["discovery"]["hits_per_term"].items())
            predicted = "<br>".join(f"`{f}`" for f in r["predicted"]) or "(none)"
            seconds = r["neatlogs_timing"]["seconds"]
            time = "n/a" if seconds is None else f"{seconds:.1f} s"
            lines.append(
                f"| {p} | {n} | {r['recall'] * 100:.0f}/{r['precision'] * 100:.0f} | {time} | {predicted} "
                f"| `{r['neatlogs_trace_id']}` | {queries} |"
            )
    lines += ["", "</details>", ""]

lines.append('<p align="center"><img src="docs/assets/benchmark-poster.webp" alt="Prism Entire benchmark poster" width="100%"></p>')
(ROOT / "BENCHMARK.md").write_text("\n".join(lines).rstrip() + "\n")
